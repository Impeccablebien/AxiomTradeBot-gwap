"""
Configuration and setup example for AxiomTradingBot
Shows how to set up and configure the bot
"""

import base64
import os
from pathlib import Path

def setup_configuration():
    """Setup bot configuration"""
    
    print("🔧 AxiomTradingBot Configuration Setup")
    print("=" * 50)
    
    # Check if config already exists
    config_path = Path("config/config.yaml")
    if config_path.exists():
        print(f"✅ Configuration file already exists at {config_path}")
        response = input("Do you want to overwrite it? (y/N): ")
        if response.lower() != 'y':
            print("Configuration setup cancelled")
            return
    
    print("\\n📧 AxiomTrade Account Setup")
    email = input("Enter your AxiomTrade email: ")
    
    print("\\n🔐 Password Encoding")
    print("Your password needs to be base64 encoded for security.")
    password = input("Enter your AxiomTrade password: ")
    
    # Encode password to base64
    encoded_password = base64.b64encode(password.encode()).decode()
    
    print("\\n💰 Trading Configuration")
    buy_amount = float(input("Default buy amount (SOL) [0.1]: ") or "0.1")
    max_position = float(input("Maximum position size (SOL) [1.0]: ") or "1.0")
    take_profit = float(input("Default take profit % [50]: ") or "50")
    stop_loss = float(input("Default stop loss % [20]: ") or "20")
    
    print("\\n🎯 Token Sniping Settings")
    enable_sniping = input("Enable token sniping? (Y/n): ").lower() != 'n'
    
    if enable_sniping:
        min_liquidity = float(input("Minimum liquidity (SOL) [5.0]: ") or "5.0")
        max_buy_tax = float(input("Maximum buy tax % [10]: ") or "10")
        max_sell_tax = float(input("Maximum sell tax % [10]: ") or "10")
    
    print("\\n🔔 Discord Notifications")
    enable_discord = input("Enable Discord notifications? (y/N): ").lower() == 'y'
    discord_webhook = ""
    
    if enable_discord:
        discord_webhook = input("Enter Discord webhook URL: ")
    
    # Create configuration content
    config_content = f"""# AxiomTradingBot Configuration
# Generated by setup script

# AxiomTrade API Configuration
axiom_trade:
  email: "{email}"
  password: "{encoded_password}"
  base_url: "https://api6.axiom.trade"

# Trading Configuration
trading:
  default_buy_amount: {buy_amount}
  max_position_size: {max_position}
  take_profit_percentage: {take_profit}
  stop_loss_percentage: {stop_loss}
  max_positions: 10
  min_liquidity: 5.0
  max_slippage: 5.0

# Token Sniping Configuration
sniping:
  enabled: {str(enable_sniping).lower()}
  min_liquidity: {min_liquidity if enable_sniping else 5.0}
  max_buy_tax: {max_buy_tax if enable_sniping else 10.0}
  max_sell_tax: {max_sell_tax if enable_sniping else 10.0}
  auto_sell_delay: 60
  blacklisted_tokens: []
  whitelisted_tokens: []

# Wallet Tracking Configuration  
wallet_tracking:
  enabled: true
  target_wallets: []  # Add wallet addresses here
  copy_percentage: 50.0
  min_trade_size: 0.01
  max_copy_amount: 1.0
  delay_seconds: 1

# Risk Management
risk_management:
  max_daily_loss: 1.0
  max_position_risk: 0.1
  portfolio_rebalance_threshold: 0.2
  emergency_stop_loss: 50.0

# Notifications
notifications:
  discord:
    enabled: {str(enable_discord).lower()}
    webhook_url: "{discord_webhook}"
  log_level: "INFO"
  enable_trade_alerts: true
  enable_error_alerts: true
"""
    
    # Create config directory if it doesn't exist
    config_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write configuration file
    with open(config_path, 'w') as f:
        f.write(config_content)
    
    print(f"\\n✅ Configuration saved to {config_path}")
    print("\\n📝 Next Steps:")
    print("1. Review and adjust the configuration if needed")
    print("2. Add profitable wallet addresses to wallet_tracking.target_wallets")
    print("3. Test with small amounts first")
    print("4. Run the bot with: python examples/basic_bot.py")
    
    # Security reminder
    print("\\n🔒 Security Reminder:")
    print("- Your password is base64 encoded (NOT encrypted)")
    print("- Keep your config file secure and private")
    print("- Never share your configuration file")
    print("- Consider using environment variables for sensitive data")

def verify_dependencies():
    """Verify that all required dependencies are installed"""
    
    print("\\n🔍 Checking Dependencies...")
    
    required_packages = [
        'requests',
        'asyncio',
        'websockets',
        'yaml',
        'pandas',
        'numpy'
    ]
    
    missing_packages = []
    
    for package in required_packages:
        try:
            __import__(package)
            print(f"✅ {package}")
        except ImportError:
            print(f"❌ {package} - MISSING")
            missing_packages.append(package)
    
    if missing_packages:
        print(f"\\n📦 Missing packages: {', '.join(missing_packages)}")
        print("Install with: pip install -r requirements.txt")
        return False
    else:
        print("\\n✅ All dependencies are installed!")
        return True

def main():
    """Main setup function"""
    
    print("🚀 Welcome to AxiomTradingBot Setup!")
    print()
    
    # Verify dependencies
    if not verify_dependencies():
        return
    
    # Setup configuration
    setup_configuration()
    
    print("\\n🎉 Setup complete! You're ready to start trading.")
    print("\\n⚠️  Important Disclaimers:")
    print("- Trading cryptocurrencies involves significant risk")
    print("- Only invest what you can afford to lose")
    print("- This bot is for educational purposes")
    print("- Test with small amounts first")
    print("- Always do your own research")

if __name__ == "__main__":
    main()
